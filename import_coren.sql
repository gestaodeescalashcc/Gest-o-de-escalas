-- 2) Tenta casar cada linha do excel com profissional existente
matched AS (
  SELECT
    i.nome_excel,
    i.coren,
    p.id AS prof_id,
    p.full_name AS nome_banco,
    COUNT(*) OVER (PARTITION BY i.nome_excel) AS qtd_matches
  FROM import i
  JOIN professionals p
    ON norm_name(p.full_name) = norm_name(i.nome_excel)
  WHERE p.active = true
)
-- 3) Atualiza só os que tem match único
UPDATE professionals p
SET coren = m.coren
FROM matched m
WHERE p.id = m.prof_id
  AND m.qtd_matches = 1;

-- 4) Relatório: o que entrou
SELECT
  COUNT(*) FILTER (WHERE coren IS NOT NULL) AS profissionais_com_coren,
  COUNT(*) FILTER (WHERE coren IS NULL) AS profissionais_sem_coren
FROM professionals
WHERE active = true;

