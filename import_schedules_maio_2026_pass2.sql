exact_match AS (
  SELECT i.*, p.id AS prof_id
  FROM imported i
  JOIN professionals p ON norm_name(p.full_name) = norm_name(i.name_excel) AND p.active = true
),
unmatched AS (
  SELECT i.* FROM imported i
  WHERE NOT EXISTS (SELECT 1 FROM exact_match e WHERE e.sector=i.sector AND e.name_excel=i.name_excel AND e.day=i.day AND e.code=i.code)
),
-- Pra cada unmatched, conta quantos profissionais ativos tem o mesmo first+last
fuzzy AS (
  SELECT u.*, p.id AS prof_id,
         COUNT(*) OVER (PARTITION BY u.sector, u.name_excel, u.day) AS qtd_candidatos
  FROM unmatched u
  JOIN professionals p ON first_last(p.full_name) = first_last(u.name_excel) AND p.active = true
),
all_matches AS (
  SELECT sector, name_excel, day, code, prof_id FROM exact_match
  UNION ALL
  SELECT sector, name_excel, day, code, prof_id FROM fuzzy WHERE qtd_candidatos = 1
)
INSERT INTO shifts (
  professional_id, schedule_id, department_id,
  shift_date, shift_type, start_time, end_time
)
SELECT
  m.prof_id,
  ms.id,
  d.id,
  make_date(2026, 5, m.day),
  m.code,
  CASE m.code
    WHEN 'P'  THEN '07:00'::time WHEN 'SD' THEN '07:00'::time
    WHEN 'SN' THEN '19:00'::time WHEN 'M'  THEN '07:00'::time
    WHEN 'M2' THEN '08:00'::time WHEN 'T'  THEN '12:00'::time
    WHEN 'MT' THEN '08:00'::time ELSE '00:00'::time
  END,
  CASE m.code
    WHEN 'P'  THEN '07:00'::time WHEN 'SD' THEN '19:00'::time
    WHEN 'SN' THEN '07:00'::time WHEN 'M'  THEN '13:00'::time
    WHEN 'M2' THEN '12:00'::time WHEN 'T'  THEN '18:00'::time
    WHEN 'MT' THEN '17:00'::time ELSE '00:00'::time
  END
FROM all_matches m
JOIN departments d ON d.name = m.sector
JOIN monthly_schedules ms ON ms.department_id = d.id AND ms.month = '2026-05-01'::date
ON CONFLICT DO NOTHING;

