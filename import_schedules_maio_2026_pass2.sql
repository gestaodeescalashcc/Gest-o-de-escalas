-- 1) Funções auxiliares
CREATE OR REPLACE FUNCTION norm_name(s text) RETURNS text AS $$
  SELECT lower(translate(s,
    'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ',
    'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'));
$$ LANGUAGE SQL IMMUTABLE;

-- Pega "primeira palavra + última palavra" do nome (sem pontos)
CREATE OR REPLACE FUNCTION first_last(s text) RETURNS text AS $$
  WITH cleaned AS (
    SELECT regexp_split_to_array(
      trim(regexp_replace(s, '[.,]', '', 'g')),
      '\s+'
    ) AS words
  )
  SELECT lower(translate(
    words[1] || ' ' || words[array_length(words, 1)],
    'áàâãäéèêëíìîïóòôõöúùûüçÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇ',
    'aaaaaeeeeiiiiooooouuuucAAAAAEEEEIIIIOOOOOUUUUC'))
  FROM cleaned;
$$ LANGUAGE SQL IMMUTABLE;

